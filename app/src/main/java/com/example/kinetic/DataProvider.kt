    private fun normalizeExerciseName(name: String): String {
        return name.lowercase()
            .replace(Regex("\\s*\\(.*?\\)"), "")
            .replace(Regex("\\s+"), " ")
            .trim()
    }

    fun getDeduplicatedExercises(group: String): List<ExerciseDefinition> {
        val exercises = exercitiiPeGrupa[group] ?: emptyList()
        val seen = mutableSetOf<String>()
        return exercises.filter { ex ->
            val normalized = normalizeExerciseName(ex.name)
            if (normalized in seen) false
            else { seen.add(normalized); true }
        }
    }

